import assert from 'node:assert/strict';
import test from 'node:test';
import {
  assessLocalCloneReadiness,
  evaluateProviderRetirement,
  type VoiceCorpusManifest,
  type VoiceCorpusSample,
} from '../packages/voice/src/voice-independence.js';

const sha = (n: number) => n.toString(16).padStart(64, '0');
const sample = (id: string, seconds: number, extra: Partial<VoiceCorpusSample> = {}): VoiceCorpusSample => ({
  id,
  provenance: 'original-recording',
  durationSeconds: seconds,
  sha256: sha(id.length * 1000 + seconds),
  storedLocally: true,
  hasTranscript: true,
  cleanAudioConfirmed: true,
  ...extra,
});
const consent = { grantedAt: '2026-11-04T10:00:00Z', grantedBy: 'subject' as const, scope: 'Voz de Janus, uso interno' };

test('original recordings with consent make the local clone ready', () => {
  const manifest: VoiceCorpusManifest = {
    subject: 'jean',
    consent,
    samples: [sample('a', 40), sample('bb', 30)],
  };
  const result = assessLocalCloneReadiness(manifest);
  assert.equal(result.ready, true);
  assert.equal(result.usableSeconds, 70);
  assert.deepEqual(result.usableSampleIds, ['a', 'bb']);
  assert.deepEqual(result.blockers, []);
});

test('audio generated by a provider is never accepted as clone corpus', () => {
  const manifest: VoiceCorpusManifest = {
    subject: 'jean',
    consent,
    samples: [sample('tts-take', 120, { provenance: 'provider-output' })],
  };
  const result = assessLocalCloneReadiness(manifest);
  assert.equal(result.ready, false);
  assert.equal(result.usableSeconds, 0);
  assert.match(result.blockers.join(' '), /generado por un proveedor/);
});

test('missing or revoked consent, minors and thin corpora block readiness', () => {
  assert.match(assessLocalCloneReadiness({ subject: 'jean', samples: [sample('a', 60)] }).blockers.join(' '), /consentimiento/i);

  const revoked = assessLocalCloneReadiness({
    subject: 'jean',
    consent: { ...consent, revokedAt: '2026-11-05T00:00:00Z' },
    samples: [sample('a', 60)],
  });
  assert.equal(revoked.ready, false);
  assert.match(revoked.blockers.join(' '), /revocado/);

  const minor = assessLocalCloneReadiness({
    subject: 'kendra',
    subjectIsMinor: true,
    consent,
    samples: [sample('a', 60)],
  });
  assert.equal(minor.ready, false);
  assert.match(minor.blockers.join(' '), /tutor/);

  const thin = assessLocalCloneReadiness({ subject: 'jean', consent, samples: [sample('a', 4)] });
  assert.equal(thin.ready, false);
  assert.match(thin.blockers.join(' '), /insuficiente/);
});

test('unknown provenance, duplicates and unreviewed audio are excluded with a warning', () => {
  const dup = sample('dup', 30);
  const manifest: VoiceCorpusManifest = {
    subject: 'jean',
    consent,
    samples: [
      sample('ok', 30),
      dup,
      { ...dup, id: 'dup-copy' },
      sample('mystery', 30, { provenance: 'unknown' }),
      sample('noisy', 30, { cleanAudioConfirmed: false }),
      sample('notext', 30, { hasTranscript: false }),
      sample('remote', 30, { storedLocally: false }),
    ],
  };
  const result = assessLocalCloneReadiness(manifest);
  assert.equal(result.ready, true);
  assert.equal(result.usableSeconds, 60);
  assert.equal(result.warnings.length, 5);
});

test('the provider cannot be retired until every independence gate is documented', () => {
  const all = {
    localSynthesisVerifiedOffline: true,
    coreFlowWorksWithoutProviderKey: true,
    consentAndRevocationVerified: true,
    benchmarkRecorded: true,
    founderAcceptedLocalVoice: true,
  };
  assert.deepEqual(evaluateProviderRetirement(all), { canRetireProvider: true, missing: [] });

  const partial = evaluateProviderRetirement({ ...all, benchmarkRecorded: false, founderAcceptedLocalVoice: false });
  assert.equal(partial.canRetireProvider, false);
  assert.equal(partial.missing.length, 2);
});
